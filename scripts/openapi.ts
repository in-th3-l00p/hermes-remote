// Writes packages/hermes-api/openapi.json and the client's generated types.
// `bun scripts/openapi.ts --check` fails instead of writing when either is stale.
import openapiTS, { astToString } from "openapi-typescript";
import { canonicalOpenApi } from "../packages/hermes-api/src/openapi/index.ts";

const SPEC = "packages/hermes-api/openapi.json";
const TYPES = "packages/hermes-ts/src/openapi.ts";
const check = process.argv.includes("--check");

const doc = await canonicalOpenApi();
// The version changes every release; keep the snapshot about the API shape.
const stable = { ...doc, info: { ...(doc["info"] as object), version: "0.0.0" } };
const json = `${JSON.stringify(stable, null, 2)}\n`;
const types =
  "// Generated by scripts/openapi.ts from the OpenAPI document. Do not edit.\n" +
  "/* eslint-disable */\n" +
  astToString(await openapiTS(stable as never));

let stale = false;
for (const [path, content] of [
  [SPEC, json],
  [TYPES, types],
] as const) {
  const file = Bun.file(path);
  const current = (await file.exists()) ? await file.text() : null;
  if (current === content) {
    continue;
  }
  if (check) {
    console.error(`${path} is out of date: run bun scripts/openapi.ts`);
    stale = true;
  } else {
    await Bun.write(path, content);
    console.log(`wrote ${path}`);
  }
}
process.exit(stale ? 1 : 0);
